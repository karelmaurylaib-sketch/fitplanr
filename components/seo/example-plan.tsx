import { generatePlan, type Answers, type Plan } from "@/lib/engine/generate";

// Real output of FitPlanr's engine (lib/engine), rendered at build time. Nothing here is typed by hand.

export const EXAMPLES = {
  twoDumbbells: { goal: "muscle", level: "new", days: 3, minutes: 45, protect: [], gear: ["dumbbells"], dbMax: 25 },
  homeBench: { goal: "muscle", level: "new", days: 3, minutes: 45, protect: [], gear: ["adjustable", "bench"], dbMax: 50 },
  fullGym: { goal: "muscle", level: "new", days: 3, minutes: 60, protect: [], gear: ["dumbbells", "adjustable", "barbell", "rack", "bench", "cables", "machines", "pullup"], dbMax: 80 },
} satisfies Record<string, Answers>;

const sec = (s: number) => (s >= 60 ? `${Math.floor(s / 60)}:${String(s % 60).padStart(2, "0")}` : `${s}s`);
const reps = (e: Plan["weeks"][number]["days"][number]["exercises"][number]) => (e.unit === "sec" ? `${e.range[0]}–${e.range[1]} s` : `${e.range[0]}–${e.range[1]}`);

/** Week 1 of a real plan: every day, every exercise, sets × rep range, starting weight and rest. */
export function ExampleWeek({ answers, days }: { answers: Answers; days?: number[] }) {
  const plan = generatePlan(answers);
  const week = plan.weeks[0];
  const shown = days ? week.days.filter((d) => days.includes(d.day)) : week.days;
  return (
    <figure className="not-prose my-8 overflow-hidden rounded-[22px] border border-line-2 bg-card">
      <figcaption className="border-b border-line px-5 py-4">
        <div className="font-mono text-[11px] uppercase tracking-[0.16em] text-lime">[ Real FitPlanr output ]</div>
        <div className="mt-1 font-display text-[26px] font-bold uppercase leading-none">{plan.title}</div>
        <div className="mt-1 text-[14px] text-muted">{plan.summary} Split: {plan.split}.</div>
      </figcaption>
      <div className="divide-y divide-line">
        {shown.map((d) => (
          <div key={d.day} className="px-5 py-4">
            <div className="flex items-baseline justify-between gap-3">
              <div className="text-[16px] font-semibold">
                {d.weekday} · {d.name} <span className="font-normal text-muted">· {d.focus}</span>
              </div>
              <div className="shrink-0 font-mono text-[12px] text-muted">~{d.minutes} min</div>
            </div>
            <ul className="mt-2 divide-y divide-line">
              {d.exercises.map((e) => (
                <li key={e.slot} className="grid gap-x-4 gap-y-0.5 py-2.5 text-[14px] sm:grid-cols-[1fr_auto]">
                  <span className="font-medium">{e.name}</span>
                  <span className="text-fg/75 tabular-nums sm:text-right">
                    <b className="font-semibold text-fg">{e.sets} × {reps(e)}</b> · {e.loadLabel} · rest {sec(e.rest)}
                  </span>
                </li>
              ))}
            </ul>
          </div>
        ))}
      </div>
    </figure>
  );
}

/** One exercise across the 4 weeks: the progression the engine writes. */
export function ExampleProgression({ answers, day = 0, exercise = 0 }: { answers: Answers; day?: number; exercise?: number }) {
  const plan = generatePlan(answers);
  const rows = plan.weeks.map((w) => ({ w, e: w.days[day].exercises[exercise] }));
  const name = rows[0].e.name;
  return (
    <figure className="not-prose my-8 rounded-[22px] border border-line-2 bg-card p-5">
      <div className="font-mono text-[11px] uppercase tracking-[0.16em] text-lime">[ {name} · weeks 1 → 4 ]</div>
      <div className="mt-1 text-[14px] text-muted">{plan.summary}</div>
      <ol className="mt-4 grid gap-2 sm:grid-cols-4">
        {rows.map(({ w, e }) => (
          <li key={w.week} className={`rounded-2xl border p-4 ${w.week === 4 ? "border-lime/50 bg-lime/[0.07]" : "border-line bg-white/[0.02]"}`}>
            <div className="font-mono text-[11px] uppercase tracking-[0.14em] text-muted">Week {w.week} · {w.focus}</div>
            <div className="mt-1 font-display text-[30px] font-bold leading-none tabular-nums">
              {e.sets} × {e.target}
            </div>
            <div className="mt-1 text-[13px] text-fg/80">{e.loadLabel}{e.tempo ? ` · tempo ${e.tempo}` : ""}</div>
            {e.note && <div className="mt-2 text-[12px] text-lime">{e.note}</div>}
          </li>
        ))}
      </ol>
      <figcaption className="mt-3 text-[12px] text-dim">Generated by FitPlanr&apos;s engine for these answers. Your plan changes with your gear, goal, days and time.</figcaption>
    </figure>
  );
}
